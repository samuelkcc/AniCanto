"""Generate the Swift catalog from the same data embedded by Rust and read by Python."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def generated():
    value=(ROOT/'Resources/production-contract.json').read_text()
    return '// Generated by scripts/generate_contract.py. Edit production-contract.json.\nimport Foundation\n\nenum StudioContractCatalog {\n    static let data = #"""\n'+value+'"""#.data(using:.utf8)!\n}\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    dest=ROOT/'Sources/StudioContractCatalog.swift'
    if args.check:
        if not dest.is_file() or dest.read_text()!=generated():raise SystemExit('Swift catalog is stale; run scripts/generate_contract.py')
    else:dest.write_text(generated())
